#!/usr/bin/env python3
"""Regenerate the paper index in README.md and scripts/CheckReadme.lean.

The index lists every declaration in CoordCriterion/Paper/*.lean, in file
order, with the first sentence of its docstring.  Run from lean/:

    python3 scripts/gen_index.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAPER = ROOT / "CoordCriterion" / "Paper"
README = ROOT / "README.md"
CHECK = ROOT / "scripts" / "CheckReadme.lean"
BEGIN, END = "<!-- BEGIN PAPER INDEX -->", "<!-- END PAPER INDEX -->"

# Paper order of the files.
ORDER = [
    ("S2_FunctionalCALM", "§2 Functional CALM", "sections/functional-calm.tex"),
    ("S3_CompleteCALM", "§3 Complete CALM", "sections/complete-calm.tex"),
    ("S4_Distributed", "§4.1–4.4 Distributed execution", "sections/distributed-histories.tex, sections/distributed.tex"),
    ("S4_5_CompleteCAP", "§4.5 Complete CAP", "sections/distributed.tex"),
    ("S5_Instances", "§5 Instances", "sections/instances.tex"),
    ("AppA_Notation", "Appendix A: Notation", "appendices/notation.tex"),
    ("AppB_Proofs", "Appendix B: Deferred proofs", "appendices/proof-machinery.tex"),
    ("AppB_ProofsDistributed", "Appendix B: Deferred proofs for §4", "appendices/proof-machinery.tex"),
    ("AppB_InvariantConfluence", "Appendix B: Invariant confluence", "appendices/proof-machinery.tex"),
    ("AppC_CommitmentBases", "Appendix C: Commitment bases", "appendices/commitment-bases-general.tex"),
    ("AppD_Composition", "Appendix D: Composition", "appendices/composition.tex"),
    ("AppE_Deployment", "Appendix E: Deployment", "appendices/deployment.tex"),
    ("AppF_ResponseAvailability", "Appendix F: Response availability and Gilbert–Lynch", "appendices/cap-response.tex"),
    ("AppG_TransactionBases", "Appendix G: 2PL and MVTO", "appendices/commitment-bases.tex"),
    ("AppH_Frontiers", "Appendix H: Frontiers", "appendices/frontiers.tex"),
    ("AppI_Applications", "Appendix I: Additional applications", "appendices/additional-applications.tex"),
]

DECL = re.compile(r"^(?:noncomputable\s+)?(theorem|abbrev|def|lemma|structure|inductive)\s+(«[^»]+»)", re.M)
DOC = re.compile(r"/--(.*?)-/\s*$", re.S)


def first_sentence(doc: str) -> str:
    text = " ".join(doc.split())
    m = re.match(r"(.+?[.:])(\s|$)", text)
    s = m.group(1) if m else text
    if len(s) > 160:
        s = s[:157].rstrip() + "…"
    return s.replace("|", "\\|")


def entries(path: Path):
    src = path.read_text()
    out = []
    for m in DECL.finditer(src):
        before = src[: m.start()].rstrip()
        doc = ""
        if before.endswith("-/"):
            start = before.rfind("/--")
            if start != -1:
                doc = before[start + 3 : -2]
        out.append((m.group(2), m.group(1), first_sentence(doc)))
    return out


def main():
    lines, names = [], []
    total = 0
    for stem, title, tex in ORDER:
        es = entries(PAPER / f"{stem}.lean")
        total += len(es)
        lines.append(f"\n### {title}\n")
        lines.append(f"File `Paper/{stem}.lean`; paper source `{tex}`.\n")
        lines.append("| Lean name (`CC.Paper.…`) | Kind | Paper statement (first sentence of the docstring) |")
        lines.append("|---|---|---|")
        for name, kind, doc in es:
            lines.append(f"| `{name}` | {kind} | {doc} |")
            names.append(f"CC.Paper.{name}")
    body = f"{BEGIN}\n\n{total} entries.\n" + "\n".join(lines) + f"\n\n{END}"
    readme = README.read_text()
    i, j = readme.find(BEGIN), readme.find(END)
    if i == -1 or j == -1:
        raise SystemExit("README markers not found")
    README.write_text(readme[:i] + body + readme[j + len(END):])
    CHECK.write_text(
        "import CoordCriterion\n\n"
        "/-! Generated by `scripts/gen_index.py`: every name in the README's paper index\n"
        "exists.  Run with `lake env lean scripts/CheckReadme.lean`. -/\n\n"
        + "\n".join(f"#check @{n}" for n in names)
        + "\n"
    )
    print(f"{total} entries")


if __name__ == "__main__":
    main()
